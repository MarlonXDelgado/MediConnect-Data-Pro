CREATE TABLE doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    specialty VARCHAR(100) NOT NULL,
    professional_license_number VARCHAR(40) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_doctors_professional_license UNIQUE (professional_license_number)
);

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identification_number VARCHAR(40) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    CONSTRAINT uq_patients_identification_number UNIQUE (identification_number)
);

CREATE TABLE medical_offices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL,
    office_name VARCHAR(100) NOT NULL,
    address VARCHAR(200) NOT NULL,
    room_number VARCHAR(30) NOT NULL,
    CONSTRAINT uq_medical_offices_doctor UNIQUE (doctor_id),
    CONSTRAINT fk_medical_offices_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    appointment_datetime TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    clinical_note_id VARCHAR(24),
    CONSTRAINT ck_appointments_status CHECK (status IN ('PROGRAMADA', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT uq_appointments_clinical_note UNIQUE (clinical_note_id),
    CONSTRAINT fk_appointments_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id),
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) REFERENCES patients (id)
);

CREATE INDEX idx_appointments_doctor_time ON appointments (doctor_id, appointment_datetime);
CREATE INDEX idx_appointments_patient_time ON appointments (patient_id, appointment_datetime);